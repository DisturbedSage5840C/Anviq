"""Render eval/report.md from the JSON results the other evaluation modules write.

    python -m app.evaluation.report --results ../eval/results --out ../eval/report.md

A result that has not been produced yet is listed as "not run", never as a pass. An offline run
(scripted model) is labelled as such: it checks the harness, not the product.
"""

import argparse
import json
from collections.abc import Mapping
from pathlib import Path
from typing import Any

from app.evaluation.citations import CITATION_TARGET, FALSE_REFUSAL_LIMIT, REFUSAL_TARGET


def _load(results: Path, name: str) -> dict[str, Any] | None:
    path = results / f"{name}.json"
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def _verdict(result: Mapping[str, Any] | None, key: str = "pass") -> str:
    if result is None:
        return "not run"
    if result.get("offline"):
        return "harness check only (offline)"
    return "PASS" if result.get(key) else "below target"


def _citation_verdict(cites: Mapping[str, Any] | None) -> str:
    """The citation row passes on its own rate, not on the combined pass flag."""
    if cites is None:
        return "not run"
    if cites.get("offline"):
        return "harness check only (offline)"
    return "PASS" if cites["citation_correct_rate"] >= CITATION_TARGET else "below target"


def _refusal_verdict(cites: Mapping[str, Any] | None) -> str:
    """The refusal row passes on refusals and false refusals alone, whatever the citation rate."""
    if cites is None:
        return "not run"
    if cites.get("offline"):
        return "harness check only (offline)"
    met = (
        cites["oos_refusal_rate"] >= REFUSAL_TARGET
        and cites["false_refusal_rate"] <= FALSE_REFUSAL_LIMIT
    )
    return "PASS" if met else "below target"


def _pct(value: float | None) -> str:
    return "n/a" if value is None else f"{value * 100:.1f}%"


def _citation_cell(cites: Mapping[str, Any] | None) -> str:
    """The strict section-level rate, with the looser course-level rate beside it when recorded."""
    if cites is None:
        return "n/a"
    strict = _pct(cites["citation_correct_rate"])
    course = cites.get("course_citation_correct_rate")
    return strict if course is None else f"{strict} section-level, {_pct(course)} course-level"


def _refusal_cell(cites: Mapping[str, Any] | None) -> str:
    """Out-of-scope refusal / false refusal, plus how the questions the books cannot answer went."""
    if cites is None:
        return "n/a / n/a"
    cell = f"{_pct(cites['oos_refusal_rate'])} / {_pct(cites['false_refusal_rate'])}"
    gap = cites.get("corpus_gap")
    if not gap:
        return cell
    return (
        f"{cell} (and {gap} questions the books do not answer, "
        f"{_pct(cites['corpus_gap_refusal_rate'])} refused)"
    )


def _seconds(ms: float) -> str:
    return f"{ms / 1000:.1f} s"


def _e2e_cell(latency: Mapping[str, Any] | None) -> str:
    """Median and p95 over every probe turn, with the sample size beside them."""
    if latency is None:
        return "n/a"
    turns = latency["all"]
    return (
        f"p50 {_seconds(turns['p50_ms'])}, p95 {_seconds(turns['p95_ms'])} over {turns['n']} turns"
    )


def _e2e_verdict(latency: Mapping[str, Any] | None) -> str:
    """Passes only when both the median and the p95 are inside the target."""
    if latency is None:
        return "not run"
    turns, target = latency["all"], latency["target"]
    met = turns["p50_ms"] <= target["p50_ms"] and turns["p95_ms"] <= target["p95_ms"]
    return "PASS" if met else "below target"


def render(results: Path) -> str:
    character = _load(results, "character")
    coach = _load(results, "coach_kappa")
    cites = _load(results, "citations")
    cost = _load(results, "latency_cost")
    latency = _load(results, "latency_e2e")
    lines = [
        "# Anviq evaluation report",
        "",
        "Generated by `python -m app.evaluation.report`. Targets: slide 9 (plan section 8).",
        "",
        "| Metric | Target | Result | Status |",
        "|---|---|---|---|",
    ]
    lines.append(
        f"| AI child keeps misconception | >=95% overall, >=90% per malrule | "
        f"{_pct(character['raw_rate']) if character else 'n/a'} raw over "
        f"{character['turns'] if character else 0} turns | {_verdict(character)} |"
    )
    lines.append(
        f"| Coach agrees with experts | mean kappa >=0.6, none <0.5 | "
        f"{coach['mean_kappa'] if coach else 'n/a'} ({coach['source'] if coach else ''}) | "
        f"{_verdict(coach)} |"
    )
    lines.append(
        f"| Citations correct | >=95% | {_citation_cell(cites)} | {_citation_verdict(cites)} |"
    )
    lines.append(
        f"| Out-of-scope refused | >=95%, <=5% false refusals | "
        f"{_refusal_cell(cites)} | {_refusal_verdict(cites)} |"
    )
    per_day = cost.get("usd_per_teacher_day") if cost else None
    lines.append(
        f"| Cost per teacher-day | <= $0.12 | {'n/a' if per_day is None else f'${per_day:.3f}'} | "
        f"{_verdict(cost, 'cost_pass')} |"
    )
    lines.append(
        f"| End-to-end latency (web room) | p50 <= 10 s, p95 <= 20 s | {_e2e_cell(latency)} | "
        f"{_e2e_verdict(latency)} |"
    )
    if character:
        lines += [
            "",
            "## Misconception retention by malrule",
            "",
            "| Malrule | Raw rate |",
            "|---|---|",
        ]
        lines += [f"| {k} | {_pct(v)} |" for k, v in character["by_malrule"].items()]
        lines += ["", "| Teacher style | Raw rate |", "|---|---|"]
        lines += [f"| {k} | {_pct(v)} |" for k, v in character["by_style"].items()]
    if coach:
        lines += ["", "## Coach kappa by criterion", "", "| Move:criterion | kappa |", "|---|---|"]
        lines += [f"| {k} | {v} |" for k, v in coach["kappa_by_criterion"].items()]
    if latency:
        lines += [
            "",
            "## End-to-end latency",
            "",
            "| Turns | n | p50 | p95 | max |",
            "|---|---|---|---|---|",
        ]
        for name in ("all", "text", "voice", "model_turns_only"):
            if name not in latency:
                continue
            row = latency[name]
            lines.append(
                f"| {name.replace('_', ' ')} | {row['n']} | {_seconds(row['p50_ms'])} | "
                f"{_seconds(row['p95_ms'])} | {_seconds(row['max_ms'])} |"
            )
        if "method" in latency:
            lines += ["", f"Method: {latency['method']}", ""]
        lines += [f"- {caveat}" for caveat in latency.get("caveats", [])]
    if cost:
        lines += [
            "",
            "## Model latency by purpose (ms)",
            "",
            "| Purpose | Calls | p50 | p95 |",
            "|---|---|---|---|",
        ]
        lines += [
            f"| {p} | {v['calls']} | {v['p50']:.0f} | {v['p95']:.0f} |"
            for p, v in cost["model_latency_ms"].items()
        ]
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--results", type=Path, default=Path("../eval/results"))
    parser.add_argument("--out", type=Path, default=Path("../eval/report.md"))
    args = parser.parse_args()
    args.out.write_text(render(args.results), encoding="utf-8")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
